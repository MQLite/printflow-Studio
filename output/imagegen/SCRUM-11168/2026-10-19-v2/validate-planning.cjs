const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const cp=require('node:child_process');
const root=__dirname, repo=path.resolve(root,'../../../..');
const read=n=>fs.readFileSync(path.join(root,n),'utf8');
const hash=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const approval=JSON.parse(read('design-approval.json'));
const planPath=approval.implementation.plan;
const plan=fs.readFileSync(planPath,'utf8');
const checks=[];
function check(name,condition){checks.push({name,result:condition?'PASS':'FAIL'});}
check('Required plan header and spec',plan.startsWith('# SCRUM-11177 Guided WPF Theme Implementation Plan')&&['**Goal:**','**Architecture:**','**Tech Stack:**','**Spec:**','## Global Constraints','## Review Focus'].every(s=>plan.includes(s)));
check('Five testable task boundaries',(plan.match(/^## Task [1-5]:/gm)||[]).length===5);
const tasks=plan.split(/^## Task [1-5]:/m).slice(1);
check('Each task has checkbox steps and a test example',tasks.length===5&&tasks.every((task,i)=>(task.match(/^- \[ \] \*\*Step/gm)||[]).length===[5,5,5,6,7][i]&&task.includes('```csharp')));
check('Code fences balanced',(plan.match(/^```/gm)||[]).length%2===0);
const links=[...plan.matchAll(/\]\((\.\.\/[^)]+)\)/g)].map(m=>path.resolve(path.dirname(planPath),m[1]));
check('Design links exist',links.length===3&&links.every(p=>fs.existsSync(p)));
check('User full design approval recorded',approval.designApproved===true&&approval.userStatement==='通过。请继续。');
check('Three Jira design tasks confirmed Done',approval.jiraTransitions.length===3&&approval.jiraTransitions.every(t=>!t.result.isError&&JSON.parse(t.result.content.find(c=>c.type==='text').text).data.statusName==='Done'));
const manifest=JSON.parse(read('prototype-manifest.json'));
check('Manifest design status consistent',manifest.styleApproval.fullPrototypeApproved===true&&manifest.issues.slice(0,3).every(i=>i.jiraStatus==='Done'));
const verification=JSON.parse(read('verification-after-approval.json'));
check('Post approval prototype validation passed',verification.checkCount===71&&verification.passed===71&&verification.errors.length===0&&verification.expandedPrototypeApproval==='APPROVED_BY_USER');
check('Historical verification bytes retained',hash(path.join(root,'verification.json'))===approval.hashesBefore.verification);
check('Original six assets retained',verification.v1AssetsPreserved===true);
const status=cp.spawnSync('git',['status','--porcelain','--','src','tests'],{cwd:repo,encoding:'utf8'});
check('No product or test source changes',status.status===0&&status.stdout.trim()==='');
check('Physical and production verification stays NOT RUN',verification.physicalWindowDpi==='NOT RUN'&&verification.productionAutomation==='NOT RUN'&&verification.noviceAcceptance==='NOT RUN');
const failed=checks.filter(c=>c.result==='FAIL');
if(failed.length){console.log(JSON.stringify({status:'FAIL',failed}));process.exit(1);}
approval.initialPlanSha256=approval.hashesAfter.plan;
approval.hashesAfter.plan=hash(planPath);
approval.hashesAfter.spec=hash(path.join(root,'design-spec.html'));
approval.postApprovalVerification='verification-after-approval.json';
approval.planSelfReview='COMPLETE - scope coverage, task steps, resource types/interfaces, five review focus conditions and proportion checked; awaiting human plan review.';
fs.writeFileSync(path.join(root,'design-approval.json'),JSON.stringify(approval,null,2)+'\n');
const result={status:'PLANNING_AND_APPROVAL_CHECKS_PASS',checks,plan:planPath,planSha256:approval.hashesAfter.plan,productCodeStarted:false,implementationPlanReview:'PENDING'};
fs.writeFileSync(path.join(root,'planning-verification.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify({status:result.status,checks:checks.length,passed:checks.length,productCodeStarted:false,implementationPlanReview:'PENDING'}));
